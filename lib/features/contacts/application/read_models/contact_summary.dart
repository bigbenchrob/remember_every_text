import '../../domain/participant_origin.dart';

class ContactSummary {
  const ContactSummary({
    required this.participantId,
    required this.displayName,
    required this.autoGeneratedName,
    required this.totalChats,
    required this.totalMessages,
    this.lastMessageDate,
    required this.origin,
    required this.handleCount,
    this.givenName,
    this.familyName,
    this.organization,
  });

  final int participantId;

  /// The name displayed throughout the app.
  final String displayName;

  /// The algorithm-generated name from AddressBook import.
  ///
  /// This never changes and helps users identify the contact if they set a
  /// confusing override.
  final String autoGeneratedName;
  final int totalChats;
  final int totalMessages;
  final DateTime? lastMessageDate;
  final ParticipantOrigin origin;
  final int handleCount;

  /// Raw AddressBook name components shown in edit surfaces.
  final String? givenName;
  final String? familyName;
  final String? organization;

  bool get isVirtual => origin == ParticipantOrigin.overlayVirtual;

  bool get hasDisplayNameOverride => displayName != autoGeneratedName;
}
